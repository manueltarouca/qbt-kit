"""Build .torrent files from local content, with stdlib only.

Deliberately independent of the code under test. Using qbt-kit's own
`torrentcreator` endpoints to build test fixtures would make the setup depend on
the thing being verified, so a dumb separate implementation is the point.

    mktorrent.py --content ~/.cache/qbt-harness/data/pack --out pack.torrent

Content is synthetic random bytes generated by `make_content`, so piece counts
and sizes are known exactly and assertions can be precise.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import secrets

# --------------------------------------------------------------------------- #
# bencode


def bencode(value: object) -> bytes:
    if isinstance(value, bool):  # before int: bool is an int subclass
        raise TypeError("bencode has no boolean type")
    if isinstance(value, int):
        return b"i" + str(value).encode() + b"e"
    if isinstance(value, bytes):
        return str(len(value)).encode() + b":" + value
    if isinstance(value, str):
        return bencode(value.encode("utf-8"))
    if isinstance(value, (list, tuple)):
        return b"l" + b"".join(bencode(v) for v in value) + b"e"
    if isinstance(value, dict):
        out = [b"d"]
        # bencode requires keys sorted as raw byte strings
        for key in sorted(value, key=lambda k: k.encode() if isinstance(k, str) else k):
            out.append(bencode(key))
            out.append(bencode(value[key]))
        out.append(b"e")
        return b"".join(out)
    raise TypeError(f"cannot bencode {type(value).__name__}")


# --------------------------------------------------------------------------- #
# content


def make_content(root: pathlib.Path, files: dict[str, int], seed: int = 0) -> None:
    """Write deterministic-length files of random bytes."""
    root.mkdir(parents=True, exist_ok=True)
    for name, size in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("wb") as fh:
            remaining = size
            while remaining:
                chunk = min(remaining, 1 << 20)
                fh.write(secrets.token_bytes(chunk))
                remaining -= chunk


# --------------------------------------------------------------------------- #
# torrent


def build(
    content: pathlib.Path,
    piece_length: int = 1 << 18,
    announce: str | None = None,
    private: bool = True,
) -> bytes:
    """Return the bencoded .torrent for a file or directory."""
    if content.is_file():
        paths = [content]
        base = content.parent
    else:
        paths = sorted(p for p in content.rglob("*") if p.is_file())
        base = content
    if not paths:
        raise ValueError(f"no files under {content}")

    # Pieces span file boundaries, which is exactly why a pack's recovered
    # percentage after grafting individual files is never quite 100%.
    pieces = bytearray()
    buf = bytearray()
    for path in paths:
        with path.open("rb") as fh:
            while True:
                chunk = fh.read(piece_length - len(buf))
                if not chunk:
                    break
                buf += chunk
                if len(buf) == piece_length:
                    pieces += hashlib.sha1(buf).digest()  # noqa: S324 - the spec
                    buf = bytearray()
    if buf:
        pieces += hashlib.sha1(buf).digest()  # noqa: S324

    info: dict[str, object] = {
        "name": content.name,
        "piece length": piece_length,
        "pieces": bytes(pieces),
    }
    if private:
        info["private"] = 1
    if content.is_file():
        info["length"] = content.stat().st_size
    else:
        info["files"] = [
            {"length": p.stat().st_size, "path": list(p.relative_to(base).parts)} for p in paths
        ]

    meta: dict[str, object] = {"info": info, "created by": "qbt-kit tests"}
    if announce:
        meta["announce"] = announce
    return bencode(meta)


def infohash(torrent: bytes) -> str:
    """The v1 infohash, as qBittorrent reports it."""
    # Re-decode cheaply: locate the info dict by re-encoding its contents is
    # overkill here, so callers normally pass the info dict directly. For the
    # fixtures we build, bencode is deterministic, so slicing on the known key
    # is safe.
    marker = b"4:infod"
    start = torrent.index(marker) + len(marker) - 1
    depth = 0
    i = start
    while i < len(torrent):
        c = torrent[i : i + 1]
        if c == b"d" or c == b"l":
            depth += 1
            i += 1
        elif c == b"e":
            depth -= 1
            i += 1
            if depth == 0:
                break
        elif c == b"i":
            i = torrent.index(b"e", i) + 1
        elif c.isdigit():
            colon = torrent.index(b":", i)
            length = int(torrent[i:colon])
            i = colon + 1 + length
        else:
            raise ValueError(f"unexpected byte {c!r} at {i}")
    return hashlib.sha1(torrent[start:i]).hexdigest()  # noqa: S324


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--content", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--piece-length", type=int, default=1 << 18)
    ap.add_argument("--announce")
    args = ap.parse_args()
    data = build(pathlib.Path(args.content), args.piece_length, args.announce)
    with open(args.out, "wb") as fh:
        fh.write(data)
    print(f"{args.out}  {len(data)} bytes  infohash={infohash(data)}")
    print(f"  content: {args.content}  piece length: {args.piece_length}")
    print(
        f"  files:   {sum(1 for _ in pathlib.Path(args.content).rglob('*') if _.is_file())}"
        if os.path.isdir(args.content)
        else "  single file"
    )


if __name__ == "__main__":
    main()
