"""The `torrents` scope — 61 endpoints on 5.2.3, the bulk of the API.

In progress. Every entry here is written against the inventory in
inventory/release-5.2.3.json; `tools/build_coverage.py` reports what is still
missing, so the gap is always visible rather than assumed.
"""

from __future__ import annotations

from ._types import (
    Binary,
    Body,
    Endpoint,
    Hashes,
    Json,
    NoContent,
    Param,
    RawText,
    Wire,
    flag,
    integer,
    register,
    text,
)

register(
    Endpoint(
        scope="torrents",
        name="info",
        method="GET",
        summary="List torrents, optionally filtered.",
        returns=Json("TorrentInfo"),
        params=(
            text("filter", summary="all|downloading|seeding|completed|stopped|…"),
            text("category"),
            text("tag", since=(2, 8, 3)),
            text("sort"),
            flag("reverse"),
            integer("limit"),
            integer("offset"),
            Param("hashes", Wire.HASHES, summary="restrict to these hashes"),
        ),
    ),
    Endpoint(
        scope="torrents",
        name="count",
        method="GET",
        since=(2, 9, 3),
        summary="Number of torrents, cheaper than len(info).",
        returns=RawText,
    ),
    Endpoint(
        scope="torrents",
        name="properties",
        method="GET",
        summary="Detailed properties of one torrent.",
        returns=Json("TorrentProperties"),
        params=(text("hash", required=True),),
    ),
    Endpoint(
        scope="torrents",
        name="trackers",
        method="GET",
        summary="Trackers of one torrent, with status and message.",
        returns=Json("Tracker"),
        params=(text("hash", required=True),),
    ),
    Endpoint(
        scope="torrents",
        name="webseeds",
        method="GET",
        summary="Web seeds of one torrent.",
        returns=Json("WebSeed"),
        params=(text("hash", required=True),),
    ),
    Endpoint(
        scope="torrents",
        name="files",
        method="GET",
        summary="Per-file progress, size, priority. The authoritative source for "
        "completeness; on-disk resume data lags by up to an hour.",
        returns=Json("TorrentFile"),
        params=(text("hash", required=True), Param("indexes", Wire.PIPE_LIST, since=(2, 8, 2))),
    ),
    Endpoint(
        scope="torrents",
        name="pieceStates",
        method="GET",
        summary="Per-piece download state.",
        returns=Json("PieceState"),
        params=(text("hash", required=True),),
    ),
    Endpoint(
        scope="torrents",
        name="pieceHashes",
        method="GET",
        summary="Per-piece SHA-1 hashes.",
        returns=Json("PieceHashes"),
        params=(text("hash", required=True),),
    ),
    Endpoint(
        scope="torrents",
        name="pieceAvailability",
        method="GET",
        since=(2, 11, 0),
        summary="Per-piece availability across connected peers.",
        returns=Json("PieceAvailability"),
        params=(text("hash", required=True),),
        untestable="needs a second peer in the swarm",
    ),
    # ----- lifecycle. `start`/`stop` replaced `resume`/`pause` in 5.0; the old
    # names were removed, not aliased, so compat.py translates both ways.
    Endpoint(
        scope="torrents",
        name="start",
        method="POST",
        since=(2, 11, 0),
        summary="Start torrents (was `resume` before 5.0).",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes,),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="stop",
        method="POST",
        since=(2, 11, 0),
        summary="Stop torrents (was `pause` before 5.0).",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes,),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="recheck",
        method="POST",
        summary="Re-verify data against the piece hashes. A full hash pass — "
        "expensive on large torrents.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes,),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="reannounce",
        method="POST",
        since=(2, 0, 2),
        summary="Force a tracker announce.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes,),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="delete",
        method="POST",
        summary="Remove torrents, optionally deleting their files.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(
            Hashes,
            flag(
                "deleteFiles",
                required=True,
                default=False,
                summary="irreversible; never defaulted true",
            ),
        ),
        mutating=True,
        destructive=True,
    ),
    Endpoint(
        scope="torrents",
        name="add",
        method="POST",
        summary="Add torrents by URL/magnet or uploaded file.",
        returns=RawText,  # older versions answer 200 "Fails." on rejection
        body=Body.MULTIPART,
        params=(
            Param("urls", Wire.PIPE_LIST, summary="magnet or http(s) URLs"),
            Param("torrents", Wire.FILE, summary=".torrent file contents"),
            text("savepath"),
            text("category"),
            Param("tags", Wire.PIPE_LIST, since=(2, 6, 2)),
            flag("stopped", renamed=True, summary="was `paused` before 5.0"),
            flag("autoTMM", summary="let the category's save path win"),
            flag("sequentialDownload"),
            flag("firstLastPiecePrio"),
            flag("skip_checking"),
            text("rename"),
            integer("upLimit"),
            integer("dlLimit"),
            text("contentLayout", since=(2, 7, 0)),
        ),
        mutating=True,
    ),
    # ----- placement
    Endpoint(
        scope="torrents",
        name="setLocation",
        method="POST",
        summary="Move a torrent's files; qBittorrent performs the move and the "
        "torrent stays valid. Returns before the move completes.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes, text("location", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="setSavePath",
        method="POST",
        since=(2, 8, 4),
        summary="Set the save path without moving existing data.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Param("id", Wire.HASHES, required=True), text("path", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="rename",
        method="POST",
        summary="Rename a torrent (display name only).",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("hash", required=True), text("name", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="renameFile",
        method="POST",
        since=(2, 4, 0),
        summary="Rename one file inside a torrent.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(
            text("hash", required=True),
            text("oldPath", required=True, renamed=True),
            text("newPath", required=True, renamed=True),
        ),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="filePrio",
        method="POST",
        summary="Set per-file priority. Priority 0 deselects a file, which is how "
        "you skip episodes of a pack you already hold.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(
            text("hash", required=True),
            Param("id", Wire.PIPE_LIST, required=True),
            integer("priority", required=True),
        ),
        mutating=True,
    ),
    # ----- categories
    Endpoint(
        scope="torrents",
        name="categories",
        method="GET",
        since=(2, 1, 1),
        summary="All categories with their save paths.",
        returns=Json("Category"),
    ),
    Endpoint(
        scope="torrents",
        name="createCategory",
        method="POST",
        summary="Create a category, optionally with its own save path.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("category", required=True), text("savePath")),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="setCategory",
        method="POST",
        summary="Assign a category. With automatic management on, this MOVES the "
        "data to the category's save path.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes, text("category", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="setAutoManagement",
        method="POST",
        summary="Toggle automatic torrent management.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes, flag("enable", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="setForceStart",
        method="POST",
        summary="Force-start torrents. Beware: force-started torrents ignore "
        "share limits, so stop-on-complete stops applying.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes, flag("value", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="topPrio",
        method="POST",
        summary="Move torrents to the top of the queue.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(Hashes,),
        mutating=True,
    ),
    Endpoint(
        scope="torrents",
        name="export",
        method="POST",
        since=(2, 8, 14),
        summary="Export a torrent's .torrent file.",
        returns=Binary("application/x-bittorrent"),
        body=Body.URLENCODED,
        params=(text("hash", required=True),),
    ),
)

