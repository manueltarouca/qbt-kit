"""The `rss` scope — 14 endpoints, marked experimental upstream.

Upstream documents this as experimental and changes it without notice, so the
contract tests shape-check rather than assert stability. Folders and feeds share
one path namespace, separated by backslashes.
"""

from __future__ import annotations

from ._types import Body, Endpoint, Json, NoContent, Param, Wire, flag, integer, register, text

register(
    Endpoint(
        scope="rss",
        name="addFolder",
        method="POST",
        since=(2, 1, 0),
        summary="Create an RSS folder. Nested paths use backslashes.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("path", required=True),),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="addFeed",
        method="POST",
        since=(2, 1, 0),
        summary="Subscribe to a feed URL, optionally at a folder path.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("url", required=True), text("path")),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="setFeedURL",
        method="POST",
        since=(2, 9, 1),
        summary="Point an existing feed at a different URL.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("path", required=True), text("url", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="setFeedRefreshInterval",
        method="POST",
        since=(2, 11, 3),
        summary="Per-feed refresh interval in minutes.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("itemPath", required=True), integer("refreshInterval", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="removeItem",
        method="POST",
        since=(2, 1, 0),
        summary="Remove a feed or folder, and everything beneath it.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("path", required=True),),
        mutating=True,
        destructive=True,
    ),
    Endpoint(
        scope="rss",
        name="moveItem",
        method="POST",
        since=(2, 1, 0),
        summary="Move or rename a feed or folder.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("itemPath", required=True), text("destPath", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="items",
        method="GET",
        since=(2, 1, 0),
        summary="The feed tree, optionally including each feed's articles.",
        returns=Json("RssItems"),
        params=(flag("withData"),),
    ),
    Endpoint(
        scope="rss",
        name="markAsRead",
        method="POST",
        since=(2, 5, 1),
        summary="Mark one article read, or every article in a feed.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("itemPath", required=True), text("articleId")),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="refreshItem",
        method="POST",
        since=(2, 2, 1),
        summary="Refresh a feed or folder now.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("itemPath", required=True),),
        mutating=True,
    ),
    # ----- auto-download rules
    Endpoint(
        scope="rss",
        name="setRule",
        method="POST",
        since=(2, 1, 0),
        summary="Create or replace an auto-download rule. The definition is JSON "
        "inside the `ruleDef` form field.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(
            text("ruleName", required=True),
            Param("ruleDef", Wire.JSON_BLOB, required=True),
        ),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="renameRule",
        method="POST",
        since=(2, 1, 0),
        summary="Rename an auto-download rule.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("ruleName", required=True), text("newRuleName", required=True)),
        mutating=True,
    ),
    Endpoint(
        scope="rss",
        name="removeRule",
        method="POST",
        since=(2, 1, 0),
        summary="Delete an auto-download rule.",
        returns=NoContent,
        body=Body.URLENCODED,
        params=(text("ruleName", required=True),),
        mutating=True,
        destructive=True,
    ),
    Endpoint(
        scope="rss",
        name="rules",
        method="GET",
        since=(2, 1, 0),
        summary="All auto-download rules.",
        returns=Json("RssRules"),
    ),
    Endpoint(
        scope="rss",
        name="matchingArticles",
        method="GET",
        since=(2, 5, 1),
        summary="Articles a rule currently matches, grouped by feed.",
        returns=Json("MatchingArticles"),
        params=(text("ruleName", required=True),),
    ),
)
